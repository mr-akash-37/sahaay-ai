/**
 * Writes supabase/production-setup.sql: every migration (in order) followed by
 * the scheme seed, as ONE file you can paste into the Supabase SQL Editor of a
 * new cloud project. Safe to run again: the seed upserts by slug.
 *
 * Run with: npm run db:production-sql
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const migrationsDir = join(root, "supabase", "migrations");

const migrations = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

const parts = [
  "-- Sahaay AI — full database setup for a NEW Supabase cloud project.",
  "-- GENERATED by `npm run db:production-sql` — do not edit by hand.",
  "-- Paste into Supabase → SQL Editor → New query, then press Run.",
  "",
  ...migrations.flatMap((name) => [
    `-- ===== migration: ${name} =====`,
    readFileSync(join(migrationsDir, name), "utf8").trim(),
    "",
  ]),
  "-- ===== seed: built-in schemes =====",
  readFileSync(join(root, "supabase", "seed.sql"), "utf8").trim(),
  "",
];

const out = join(root, "supabase", "production-setup.sql");
writeFileSync(out, parts.join("\n"), "utf8");
console.log(`Wrote ${out} (${migrations.length} migrations + seed)`);
